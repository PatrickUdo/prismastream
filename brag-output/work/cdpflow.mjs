import puppeteer from 'puppeteer-core';
const v = await (await fetch('http://localhost:9333/json/version')).json();
const browser = await puppeteer.connect({ browserWSEndpoint: v.webSocketDebuggerUrl, defaultViewport: null });
const [page] = await browser.pages();
const errs = [];
const log = (s) => errs.push(`[${page.url().replace('https://localhost', '')}] ${s}`);
page.on('pageerror', (e) => log('pageerror: ' + (e.stack || e.message)));
page.on('console', (m) => { if (m.type() === 'error') log('console: ' + m.text()); });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const click = async (sel) => { const ok = await page.evaluate((s) => { const e = document.querySelector(s); if (e) { e.scrollIntoView(); e.click(); return true; } return false; }, sel); log('click ' + sel + ' -> ' + ok); await wait(2500); };
await page.goto('https://localhost/', { waitUntil: 'load' }); await wait(3000);
await click('a[href^="/watch/live/"]');
await page.evaluate(() => history.back()); await wait(2500); log('after back');
await click('a[href^="/title/"]');
await click('a[href*="/watch/"]');
await page.evaluate(() => history.back()); await wait(2500); log('after back 2');
await page.evaluate(() => history.back()); await wait(2500); log('after back 3');
await click('a[href="/live"]');
await click('a[href^="/watch/live/"]');
await page.keyboard.press('ArrowDown'); await wait(2000); log('zap down');
await page.keyboard.press('Escape'); await wait(2500); log('escape');
console.log(errs.join('\n'));
await browser.disconnect();
