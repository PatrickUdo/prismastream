import puppeteer from 'puppeteer-core';
const CODE = process.env.INVITE;
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900 });
const log = [];
page.on('console', (m) => { if (['error', 'warn'].includes(m.type())) log.push(`console.${m.type()}: ${m.text()}`); });
page.on('pageerror', (e) => log.push('pageerror: ' + e.message));
page.on('requestfailed', (r) => log.push(`FAILED ${r.method()} ${r.url().replace(/\?.*/, '')} ${r.failure()?.errorText}`));
page.on('response', (r) => { if (r.url().includes('backend.')) log.push(`${r.status()} ${r.request().method()} ${r.url().replace('https://backend.prismastream.patrickudo.nl', '').replace(/\?.*/, '')}`); });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await page.goto('https://prismastream.patrickudo.nl/settings/sync', { waitUntil: 'networkidle2' });
await wait(1500);
await page.evaluate(() => [...document.querySelectorAll('[role=tab]')].find((b) => /aanmaken/i.test(b.textContent))?.click());
await wait(500);
const pw = 'Probe-' + Math.random().toString(36).slice(2) + '-Xy9!';
await page.type('#acc-email', `probe-${Date.now()}@example.invalid`);
await page.type('#acc-pass', pw);
await page.type('#acc-pass2', pw);
await page.type('#acc-code', CODE);
await page.evaluate(() => document.querySelector('form.form button[type=submit]')?.click());
await wait(9000);
log.push('--- na registratie, url=' + page.url());
await page.goto('https://prismastream.patrickudo.nl/settings/sources', { waitUntil: 'networkidle2' });
await wait(4000);
log.push('--- bronnenpagina: ' + (await page.evaluate(() => document.querySelector('main')?.innerText.slice(0, 300).replace(/\s+/g, ' '))));
await page.goto('https://prismastream.patrickudo.nl/', { waitUntil: 'networkidle2' });
await wait(4000);
log.push('--- home: ' + (await page.evaluate(() => document.querySelector('main')?.innerText.slice(0, 200).replace(/\s+/g, ' '))));
console.log(log.join('\n'));
await browser.close();
